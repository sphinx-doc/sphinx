@pytest.mark.sphinx('dummy', testroot='_blank')
@pytest.mark.parametrize(
    ('epoch', 'date_format', 'expected'),
    [
        ('1439131307', '%Y-%m-%d %H:%M:%S', '2015-08-09 14:41:47'),
        ('0', '%Y-%m-%d', '1970-01-01'),
        pytest.param(
            '-1',
            '%Y-%m-%d %H:%M:%S',
            '1969-12-31 23:59:59',
            marks=pytest.mark.skipif(
                sys.platform == 'win32',
                reason='Windows does not support negative times',
            ),
        ),
        ('2208988800', '%Y-%m-%d', '2040-01-01'),
        ('0', '%%Y: %Y %%', '%Y: 1970 %'),
        (None, '%Y-%m-%d', '2035-01-02'),
        ('', '%Y-%m-%d', '2035-01-02'),
    ],
)
def test_datestamp_source_date_epoch(
    app: SphinxTestApp,
    monkeypatch: pytest.MonkeyPatch,
    frozen_utc_clock: None,
    epoch: str | None,
    date_format: str,
    expected: str,
) -> None:
    if epoch is None:
        monkeypatch.delenv('SOURCE_DATE_EPOCH', raising=False)
    else:
        monkeypatch.setenv('SOURCE_DATE_EPOCH', epoch)
    app.docutils_conf_path.write_text(
        '[general]\n'
        f'datestamp: {date_format}\n'
        'generator: yes\n'
        'source-url: https://example.org/source.rst\n',
        encoding='utf8',
    )

    with patch_docutils(app.confdir):
        doctree = restructuredtext.parse(app, 'Body.\n')

    footers = list(doctree.findall(nodes.footer))
    assert len(footers) == 1
    assert f'Generated on: {expected}.\n' in footers[0].astext()
    assert 'Generated by Docutils' in footers[0].astext()
    assert next(footers[0].findall(nodes.reference))['refuri'] == (
        'https://example.org/source.rst'
    )
    assert doctree.settings.datestamp == date_format


def test_datestamp_disabled(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv('SOURCE_DATE_EPOCH', '0')
    document = new_document('test.rst')
    document.settings.datestamp = None
    document.settings.generator = True

    paragraphs = _SphinxDecorations(document).generate_footer()

    assert paragraphs is not None
    assert 'Generated by Docutils' in paragraphs[0].astext()
    assert 'Generated on:' not in paragraphs[0].astext()
    assert document.settings.datestamp is None


def test_datestamp_restores_format_on_failure(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv('SOURCE_DATE_EPOCH', '0')
    document = new_document('test.rst')
    document.settings.datestamp = '%Y-%m-%d'

    def fail(self: Decorations) -> None:
        msg = 'footer generation failed'
        raise RuntimeError(msg)

    monkeypatch.setattr(Decorations, 'generate_footer', fail)

    with pytest.raises(RuntimeError, match='footer generation failed'):
        _SphinxDecorations(document).generate_footer()

    assert document.settings.datestamp == '%Y-%m-%d'


def test_datestamp_transform_selection() -> None:
    with pytest.warns(RemovedInSphinx10Warning):
        reader = importlib.import_module('sphinx.io').SphinxBaseReader()

    for transforms in (_READER_TRANSFORMS, reader.get_transforms()):
        if docutils.__version_info__[:2] < (1, 0):
            assert _SphinxDecorations in transforms
            assert Decorations not in transforms
        else:
            assert Decorations in transforms
            assert _SphinxDecorations not in transforms


@pytest.mark.sphinx('xml', testroot='source-date-epoch')
@pytest.mark.parametrize('parallel', [0, 2])
def test_datestamp_incremental_output(
    make_app: Callable[..., SphinxTestApp],
    app_params: _app_params,
    monkeypatch: pytest.MonkeyPatch,
    frozen_utc_clock: None,
    tmp_path: Path,
    parallel: int,
) -> None:
    args, kwargs = app_params
    docutils_conf = tmp_path / 'docutils.conf'
    docutils_conf.write_text('[general]\ndatestamp: %Y-%m-%d\n', encoding='utf8')
    monkeypatch.setenv('DOCUTILSCONFIG', str(docutils_conf))
    for index, (epoch, expected) in enumerate([
        ('0', '1970-01-01'),
        ('86400', '1970-01-02'),
        ('86400', '1970-01-02'),
    ]):
        monkeypatch.setenv('SOURCE_DATE_EPOCH', epoch)
        app = make_app(
            *args,
            **kwargs,
            parallel=parallel,
        )
        read_docnames: list[str] = []
        app.connect(
            'env-before-read-docs',
            lambda _app, _env, names, docnames=read_docnames: docnames.extend(names),
        )
        if index == 1:
            app.build(filenames=[app.srcdir / 'index.rst'])
        else:
            app.build()

        assert read_docnames == ([] if index == 2 else ['index', 'second'])
        for docname in ('index', 'second'):
            footer = next(app.env.get_doctree(docname).findall(nodes.footer))
            assert footer.astext() == f'Generated on: {expected}.\n'
            output = (app.outdir / f'{docname}.xml').read_text(encoding='utf8')
            assert f'Generated on: {expected}.' in output
        assert not app.warning.getvalue()
        app.cleanup()
